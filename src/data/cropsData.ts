export function getLocalizedCrop(crop: CropGuide, lang: LanguageCode): LocalizedCropContent {
  if (crop.translations && crop.translations[lang]) {
    return crop.translations[lang];
  }
  
  // Fallback to primary fields
  return {
    name: lang === 'te' ? crop.nameTe : lang === 'kn' ? crop.nameKn : lang === 'hi' ? crop.nameHi : crop.nameEn,
    category: crop.category,
    suitableSeason: crop.suitableSeason,
    suitableMonths: crop.suitableMonths,
    soil: crop.soil,
    landPreparation: crop.landPreparation,
    seedPlanting: crop.seedPlanting,
    irrigation: crop.irrigation,
    cropDuration: crop.cropDuration,
    fertilizerRequirements: crop.fertilizerRequirements,
    pestDiseasePrevention: crop.pestDiseasePrevention,
    harvest: crop.harvest,
    marketInfo: crop.marketInfo,
  };
}

export function getLocalizedCropName(crop: CropGuide, lang: LanguageCode): string {
  switch (lang) {
    case 'te':
      return crop.nameTe;
    case 'kn':
      return crop.nameKn;
    case 'hi':
      return crop.nameHi;
    case 'en':
    default:
      return crop.nameEn;
  }
}
