export function getCropGuide(cropId: string, lang: LanguageCode): ComprehensiveCropGuide {
  const langKey = COMPREHENSIVE_CROP_GUIDES[lang] ? lang : 'te';
  const cKey = cropId.toLowerCase();

  if (COMPREHENSIVE_CROP_GUIDES[langKey][cKey]) {
    return COMPREHENSIVE_CROP_GUIDES[langKey][cKey];
  }
  // Fallback to tomato
  return COMPREHENSIVE_CROP_GUIDES[langKey]['tomato'] || COMPREHENSIVE_CROP_GUIDES.te['tomato'];
}
